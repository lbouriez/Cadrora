import { mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { createRedactor, runLogged } from '../../../scripts/setup/runLogged.mjs';

const directories = [];
afterEach(() => { for (const directory of directories.splice(0)) rmSync(directory, { recursive: true, force: true }); });
function fixture(source) {
  const directory = mkdtempSync(join(tmpdir(), 'cadrora-log-'));
  directories.push(directory);
  const script = join(directory, 'child with spaces.cjs');
  writeFileSync(script, source);
  const messages = [];
  return {
    directory, messages,
    options: { logPath: join(directory, 'logs', 'attempt.log'), privateDirectory: directory, command: process.execPath, args: [script], cwd: directory, notify: (code) => messages.push(code) },
  };
}

describe('guided installer command logs', () => {
  it('keeps UTF-8 stdout, stderr and warnings in a log, with only fixed progress codes on screen', async () => {
    const { options, messages } = fixture(`
      console.log('\x1b[32mPréparation terminée ✓\x1b[0m');
      console.error('Missing required secrets: AUTH_PEPPER.');
      console.log('CADRORA_PROGRESS:models');
      console.log('CADRORA_PROGRESS:untrusted text');
      setTimeout(() => process.exit(0), 80);
    `);
    expect(await runLogged({ ...options, heartbeatMs: 20 })).toBe(0);
    const log = readFileSync(options.logPath, 'utf8');
    expect(log).toContain('Préparation terminée ✓');
    expect(log).toContain('[stderr] Missing required secrets: AUTH_PEPPER.');
    expect(log).not.toContain('\x1b');
    expect(messages).toContain('models');
    expect(messages).toContain('active');
    expect(messages.every((message) => ['models', 'active'].includes(message))).toBe(true);
  });

  it('redacts split output secrets and credentials generated by the command, including at EOF', async () => {
    const { options } = fixture(`
      const fs = require('node:fs');
      process.stdout.write(process.env.CLOUDFLARE_API_TOKEN.slice(0, 9));
      setTimeout(() => {
        console.log(process.env.CLOUDFLARE_API_TOKEN.slice(9));
        fs.writeFileSync('admin-credentials.env', 'ADMIN_PASSWORD=generated-private-password\\nAUTH_PEPPER=generated-private-pepper\\n');
        console.log('value: generated-private-password');
        console.error('value: generated-private-pepper');
        process.stderr.write(process.env.TURNSTILE_SECRET_KEY);
      }, 20);
    `);
    const token = 'sample-private-token-123456789';
    const secret = 'sample-turnstile-secret-987654';
    expect(await runLogged({ ...options, environment: { ...process.env, CLOUDFLARE_API_TOKEN: token, TURNSTILE_SECRET_KEY: secret } })).toBe(0);
    const log = readFileSync(options.logPath, 'utf8');
    for (const value of [token, secret, 'generated-private-password', 'generated-private-pepper']) expect(log).not.toContain(value);
    expect(log).toContain('[REDACTED]');
  });

  it('retains generated values after their temporary secret file is deleted', () => {
    const { directory } = fixture('');
    const redact = createRedactor(directory, {});
    const secretFile = join(directory, 'deploy-secrets.env');
    writeFileSync(secretFile, 'AUTH_PEPPER="private-generated-value"\n');
    expect(redact('private-generated-value')).toBe('[REDACTED]');
    rmSync(secretFile);
    expect(redact('private-generated-value')).toBe('[REDACTED]');
    expect(redact('Authorization: Bearer unrecognized-value')).not.toContain('unrecognized-value');
    expect(redact('TURNSTILE_SECRET_KEY=unrecognized-value')).not.toContain('unrecognized-value');
  });

  it('drains both streams without flooding the console and preserves command failure', async () => {
    const { options, messages } = fixture(`
      for (let i = 0; i < 2000; i++) { console.log('output ' + i); console.error('error ' + i); }
      process.exitCode = 42;
    `);
    expect(await runLogged(options)).toBe(42);
    expect(messages).toEqual([]);
    const log = readFileSync(options.logPath, 'utf8');
    expect(log).toContain('[stdout] output 1999');
    expect(log).toContain('[stderr] error 1999');
    expect(log).toContain('[exit] 42');
  });

  it('omits oversized unterminated lines instead of flushing chunks that could split a secret', async () => {
    const { options } = fixture(`process.stdout.write('x'.repeat(150000)); process.stdout.write('private-tail');`);
    expect(await runLogged(options)).toBe(0);
    const log = readFileSync(options.logPath, 'utf8');
    expect(log).toContain('Oversized output line omitted');
    expect(log).not.toContain('private-tail');
    expect(log.length).toBeLessThan(1000);
  });

  it('does not start a command if its log cannot be created, and never overwrites an earlier attempt', async () => {
    const { options, directory, messages } = fixture(`require('node:fs').writeFileSync('started', 'yes');`);
    writeFileSync(join(directory, 'existing.log'), 'previous attempt');
    expect(await runLogged({ ...options, logPath: join(directory, 'existing.log') })).toBe(1);
    expect(existsSync(join(directory, 'started'))).toBe(false);
    expect(readFileSync(join(directory, 'existing.log'), 'utf8')).toBe('previous attempt');
    expect(messages).toEqual(['log-error']);
  });

  it('fails cleanly if an executable is missing', async () => {
    const { options, directory } = fixture('');
    expect(await runLogged({ ...options, command: join(directory, 'missing.exe') })).not.toBe(0);
    expect(readFileSync(options.logPath, 'utf8')).toContain('Could not start the command');
  });
});
